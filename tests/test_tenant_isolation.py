"""Verify cross-tenant data leakage is structurally impossible across all pipeline stages."""

import numpy as np
import pytest
from fastapi import HTTPException
from qdrant_client.http import models as qmodels

from src.api.dependencies import get_tenant_id
from src.cache.semantic_cache import SemanticCache
from src.retrieval.hybrid_retriever import HybridRetriever


@pytest.mark.asyncio
async def test_tenant_id_header_missing_rejected():
    """Verify that omitting X-Tenant-ID immediately rejects request with 400."""
    with pytest.raises(HTTPException) as exc_info:
        await get_tenant_id(x_tenant_id=None)
    assert exc_info.value.status_code == 400
    assert "Missing required header" in exc_info.value.detail


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "invalid_tenant",
    [
        "ab",  # Too short (< 3 chars)
        "tenant:with:colons",  # Colons (RediSearch delimiter risk)
        "tenant with spaces",  # Spaces
        "tenant/with/slashes",  # Slash traversal
        "tenant'--",  # SQL/query injection syntax
        "tenant;drop table",  # Command injection syntax
        "tenant{injection}",  # Tag query injection syntax
        "a" * 65,  # Exceeds max length (64 chars)
    ],
)
async def test_tenant_id_header_injection_rejected(invalid_tenant: str):
    """Verify malicious or improperly formatted tenant identifiers are rejected."""
    with pytest.raises(HTTPException) as exc_info:
        await get_tenant_id(x_tenant_id=invalid_tenant)
    assert exc_info.value.status_code == 400
    assert "Invalid 'X-Tenant-ID' format" in exc_info.value.detail


