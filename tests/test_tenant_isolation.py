@pytest.mark.asyncio
async def test_semantic_cache_cross_tenant_isolation(mock_semantic_cache: SemanticCache):
    """Verify that Tenant B can NEVER hit a cached answer generated by Tenant A."""
    tenant_a = "tenant-enterprise-a"
    tenant_b = "tenant-enterprise-b"

    vector = np.random.randn(384).astype(np.float32)
    vector = vector / np.linalg.norm(vector)

    # 1. Tenant A caches a response
    stored = await mock_semantic_cache.set(
        tenant_id=tenant_a,
        query_text="What is our internal strategy?",
        query_vector=vector,
        response_text="CONFIDENTIAL TENANT A STRATEGY: Double revenue in Q4.",
        metadata={"author": "alice"},
    )
    assert stored is True

    # 2. Tenant A queries with exact identical vector -> HIT
    hit_a = await mock_semantic_cache.get(tenant_id=tenant_a, query_vector=vector)
    assert hit_a.hit is True
    assert "CONFIDENTIAL TENANT A STRATEGY" in (hit_a.response_text or "")

    # 3. Tenant B queries with the EXACT same vector and query -> MUST BE MISS!
    hit_b = await mock_semantic_cache.get(tenant_id=tenant_b, query_vector=vector)
    assert hit_b.hit is False
    assert hit_b.response_text is None


@pytest.mark.asyncio
async def test_qdrant_retrieval_tenant_filter_enforcement(mocker):
    """Verify that Qdrant query filter strictly enforces tenant isolation."""
    mock_qdrant = mocker.AsyncMock()

    # Mock Qdrant search returning results
    fake_hit = mocker.MagicMock()
    fake_hit.id = "doc-1"
    fake_hit.score = 0.95
    fake_hit.payload = {
        "tenant_id": "tenant-finance",
        "content": "Secret ledger details",
        "metadata": {},
    }
    mock_resp = mocker.MagicMock()
    mock_resp.points = [fake_hit]
    mock_qdrant.query_points.return_value = mock_resp
    mock_qdrant.search.return_value = [fake_hit]

    retriever = HybridRetriever(qdrant_client=mock_qdrant)
    query_vector = [0.1] * 384

    # Execute search for tenant-finance
    results = await retriever.retrieve_dense(
        tenant_id="tenant-finance",
        query_vector=query_vector,
        limit=5,
    )

    assert len(results) == 1
    assert results[0].chunk.content == "Secret ledger details"

    # Verify that Qdrant search/query_points was called with a MUST condition on tenant_id
    if mock_qdrant.query_points.called:
        call_kwargs = mock_qdrant.query_points.call_args.kwargs
    else:
        call_kwargs = mock_qdrant.search.call_args.kwargs
    query_filter: qmodels.Filter = call_kwargs["query_filter"]
    assert len(query_filter.must) >= 1
    condition = query_filter.must[0]
    assert condition.key == "tenant_id"
    assert condition.match.value == "tenant-finance"
